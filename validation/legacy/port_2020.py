"""Mechanically port the Sept 2020 checker to Python 3 + Regina 7.

Source: CAT0_Candidates/vertexlinkcond_prelim_results/vLinkCond.py (the code
that produced the *_results_202009*.txt files) and its constructible.py.
Output: vlinkcond_2020.py and constructible_2020.py next to this script.

Only names and syntax change; every edit is listed below and its number of
occurrences is asserted, so the algorithm is untouched:
  - Regina 5/6 names: NTriangulation -> Triangulation3,
    v.buildLinkDetail() -> (v.buildLink(), v.buildLinkInclusion())
  - Python 2 map() returned a list: map( -> _lmap( (a list-returning map)
  - Python 2 except/raise syntax in the (unused) parallel path
  - import the 2020 constructible.py under a distinct module name
"""

import os
import re
import shutil

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, '..', '..', 'CAT0_Candidates', 'vertexlinkcond_prelim_results')

src = open(os.path.join(SRC, 'vLinkCond.py')).read()

EDITS = [
    # (old, new, expected count)
    ('from constructible import', 'from constructible_2020 import', 2),
    ('v.buildLinkDetail()', '_buildLinkDetail(v)', 4),
    ('except Exception, e:', 'except Exception as e:', 2),
    ('raise Exception, e', 'raise e', 2),
]
for old, new, n in EDITS:
    assert src.count(old) == n, (old, src.count(old))
    src = src.replace(old, new)

n_map = len(re.findall(r'(?<![\w.])map\(', src))
src = re.sub(r'(?<![\w.])map\(', '_lmap(', src)

SHIM = '''
# ---- Python 3 / Regina 7 shim (added by validation/legacy/port_2020.py) ----
import regina
NTriangulation = regina.Triangulation3
def _buildLinkDetail(v): return (v.buildLink(), v.buildLinkInclusion())
def _lmap(*args): return list(map(*args))
# ----------------------------------------------------------------------------
'''
anchor = 'from functools import total_ordering\n'
assert src.count(anchor) == 1
src = src.replace(anchor, anchor + SHIM)

with open(os.path.join(HERE, 'vlinkcond_2020.py'), 'w') as f:
    f.write('# GENERATED by port_2020.py from vertexlinkcond_prelim_results/vLinkCond.py'
            ' -- do not edit\n' + src)
shutil.copy(os.path.join(SRC, 'constructible.py'),
            os.path.join(HERE, 'constructible_2020.py'))
print('ported; map() calls rewritten:', n_map)
